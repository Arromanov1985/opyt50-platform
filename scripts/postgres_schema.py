"""Generate PostgreSQL DDL from the current checked-in SQLite table definitions.

Preparation only: this module never connects to PostgreSQL or modifies data.
The result must be reviewed and validated against an isolated PG instance
before it is used for a migration.
"""
from __future__ import annotations

import re

from app.db import SCHEMA
from app.release02 import MIGRATION

UTC_TEXT_TIMESTAMP = (
    "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', "
    "'YYYY-MM-DD HH24:MI:SS')"
)


def postgres_schema() -> str:
    """Render known SQLite DDL into PostgreSQL-compatible DDL.

    This is deliberately limited to the two known project schema constants.
    Unknown SQLite constructs fail rather than being silently translated.
    """
    schema = SCHEMA + "\n" + MIGRATION
    schema = re.sub(r"^\s*PRAGMA\s+[^;]+;\s*$", "", schema, flags=re.MULTILINE | re.IGNORECASE)
    schema = re.sub(
        r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        schema, flags=re.IGNORECASE,
    )
    schema = re.sub(
        r"datetime\s*\(\s*'now'\s*\)",
        UTC_TEXT_TIMESTAMP, schema, flags=re.IGNORECASE,
    )
    forbidden = (r"\bPRAGMA\b", r"\bAUTOINCREMENT\b", r"datetime\s*\(",
                 r"\bWITHOUT\s+ROWID\b", r"\bSTRICT\s*;")
    for pattern in forbidden:
        if re.search(pattern, schema, re.IGNORECASE):
            raise ValueError("Unsupported SQLite DDL construct: " + pattern)
    return "-- Generated from app.db.SCHEMA and app.release02.MIGRATION; review before use.\n" + schema


if __name__ == "__main__":
    print(postgres_schema())
