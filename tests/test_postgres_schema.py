"""No external DB or credentials required for the schema preparation checks."""
import re

from scripts.postgres_schema import postgres_schema


def test_postgres_schema_contains_core_and_release02_tables():
    sql = postgres_schema()
    names = set(re.findall(r"CREATE TABLE IF NOT EXISTS\s+(\w+)", sql))
    assert {"users", "candidate_profiles", "employer_profiles", "vacancies",
            "invitations", "sessions", "demo_transactions",
            "job_applications", "application_events", "candidate_favorites",
            "account_controls", "email_tokens", "email_outbox",
            "vacancy_updates", "vacancy_update_recipients"}.issubset(names)


def test_no_sqlite_only_ddl_is_emitted():
    sql = postgres_schema()
    assert "AUTOINCREMENT" not in sql
    assert "PRAGMA " not in sql
    assert "datetime('now')" not in sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql
    assert "CURRENT_TIMESTAMP AT TIME ZONE 'UTC'" in sql


def test_schema_preserves_key_privacy_and_uniqueness_constraints():
    sql = postgres_schema()
    assert "UNIQUE(vacancy_id,candidate_id)" in sql
    assert "invitation_id INTEGER NOT NULL UNIQUE" in sql
    assert "share_consent INTEGER NOT NULL DEFAULT 0" in sql
    assert "contact_shared INTEGER NOT NULL DEFAULT 0" in sql
